const esbuild = require('esbuild');
const path = require('node:path');
async function build() {
  await esbuild.build({entryPoints:[path.join(__dirname,'../src/native.js')],outfile:path.join(__dirname,'../providers/anime-sama.js'),
    bundle:true,platform:'neutral',format:'cjs',target:'es2018',external:['cheerio'],
    supported:{'async-await':false},legalComments:'inline',charset:'utf8',
    banner:{js:'// Generated by npm run build. Edit src/ and config.json. GPL-3.0-or-later.'}});
  console.log('Built providers/anime-sama.js');
}
build().catch(e => {console.error(e);process.exitCode=1;});
